/* ==================== SSD1306 初始化序列 ==================== */
static const uint8_t s_init_cmds[] = {
    0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
    0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1,
    0xDB, 0x40, 0xA4, 0xA6, 0x8D, 0x14, 0xAF
};

/* ==================== 硬件 I2C0 读写 (与 MPU6050 共享总线) ==================== */

/* I2C0 写 SSD1306: 控制字节 + 数据字节, 阻塞等待完成 */
static void oled_i2c_write(uint8_t ctrl, uint8_t data)
{
    uint8_t buf[2] = {ctrl, data};
    while (!(DL_I2C_getControllerStatus(OLED_I2C_INST) & DL_I2C_CONTROLLER_STATUS_IDLE)) {}
    DL_I2C_fillControllerTXFIFO(OLED_I2C_INST, buf, 2);
    DL_I2C_startControllerTransfer(OLED_I2C_INST, OLED_I2C_ADDR,
                                    DL_I2C_CONTROLLER_DIRECTION_TX, 2);
    while (DL_I2C_getControllerStatus(OLED_I2C_INST) & DL_I2C_CONTROLLER_STATUS_BUSY) {}
}

/* ==================== SSD1306 命令/数据写入 ==================== */

static void oled_write_cmd(uint8_t cmd)
{
    oled_i2c_write(0x00, cmd);   /* Co=0, D/C=0 → 命令 */
}

static void oled_write_data(uint8_t data)
{
    oled_i2c_write(0x40, data);   /* Co=0, D/C=1 → 数据 */
}

static void oled_set_pos(uint8_t x, uint8_t y)
{
    oled_write_cmd(0xB0 + y);                    /* 页地址 */
    oled_write_cmd(((x & 0xF0) >> 4) | 0x10);   /* 列高 4 位 */
    oled_write_cmd(x & 0x0F);                    /* 列低 4 位 */
}

/* ==================== API 实现 ==================== */

void AppOLED_Init(void)
{
    /* I2C0 已由 SysConfig 初始化 (与 MPU6050 共享), 无需额外 GPIO 配置。
     * MPU6050 地址 0x68, SSD1306 地址 0x3C, 不冲突。 */

    /* 等待 OLED 上电稳定 */
    delay_cycles(CPUCLK_FREQ / 5);

    /* 发送初始化命令序列 */
    uint8_t i;
    for (i = 0; i < sizeof(s_init_cmds); i++) {
        oled_write_cmd(s_init_cmds[i]);
    }

    AppOLED_Clear();
}

void AppOLED_Clear(void)
{
    uint8_t page, col;
    for (page = 0; page < 8; page++) {
        oled_set_pos(0, page);
        for (col = 0; col < 128; col++) {
            oled_write_data(0x00);
        }
    }
}

void AppOLED_ShowString(uint8_t x, uint8_t y, const char *str, uint8_t size)
{
    uint8_t j = 0;
    uint8_t c, i;
    while (str[j] != '\0') {
        if (y > 7) break;
        c = str[j] - ' ';

        if (size == 16) {
            /* 8x16: 上半 8 字节在第 y 页, 下半 8 字节在第 y+1 页 */
            oled_set_pos(x, y);
            for (i = 0; i < 8; i++) oled_write_data(F8X16[c * 16 + i]);
            oled_set_pos(x, y + 1);
            for (i = 0; i < 8; i++) oled_write_data(F8X16[c * 16 + i + 8]);
            x += 8;
        } else {
            /* 6x8: 单页 6 字节 */
            oled_set_pos(x, y);
            for (i = 0; i < 6; i++) oled_write_data(F6x8[c][i]);
            x += 6;
        }

        if (size == 16 && x > 120) { x = 0; y += 2; }
        if (size != 16 && x > 122) { x = 0; y += 1; }
        j++;
    }
}

void AppOLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len, uint8_t size)
{
    uint8_t t;
    uint32_t div = 1;
    uint8_t enshow = 0;
    uint8_t w = (size == 16) ? 8 : 6;

    for (t = 0; t < len - 1; t++) div *= 10;

    for (t = 0; t < len; t++) {
        uint8_t digit = (num / div) % 10;
        if (enshow == 0 && t < len - 1) {
            if (digit == 0) {
                /* 前导空格 */
                char sp[2] = " ";
                AppOLED_ShowString(x + w * t, y, sp, size);
                div /= 10;
                continue;
            } else {
                enshow = 1;
            }
        }
        char ch[2] = { digit + '0', '\0' };
        AppOLED_ShowString(x + w * t, y, ch, size);
        div /= 10;
    }
}

void AppOLED_ShowTimeAt(uint8_t x, uint8_t y, uint32_t ms, uint8_t size)
{
    /* mm:ss.s 格式 */
    uint32_t total_tenths = ms / 100;   /* 0.1 秒单位 */
    uint8_t minutes = total_tenths / 600;
    uint8_t seconds = (total_tenths / 10) % 60;
    uint8_t tenths  = total_tenths % 10;
    uint8_t w = (size == 16) ? 8 : 6;

    /* mm */
    AppOLED_ShowNum(x, y, minutes, 2, size);
    /* : */
    AppOLED_ShowString(x + w * 2, y, ":", size);
    /* ss */
    AppOLED_ShowNum(x + w * 3, y, seconds, 2, size);
    /* . */
    AppOLED_ShowString(x + w * 5, y, ".", size);
    /* s (0.1s) */
    AppOLED_ShowNum(x + w * 6, y, tenths, 1, size);
}

void AppOLED_ShowTime(uint32_t ms)
{
    /* 居中大字显示: 16x16 字号, 7 个字符宽 = 56 像素, 居中 x=(128-56)/2=36 */
    AppOLED_ShowTimeAt(36, 3, ms, 16);
}
